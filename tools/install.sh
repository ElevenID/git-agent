#!/usr/bin/env bash
# Install the single reviewed Bash command without changing profiles or PATH.
set -euo pipefail

ga_install_fail() { printf 'Install failed: %s\n' "$*" >&2; exit 2; }
ga_install_usage() {
    printf '%s\n' 'Usage: bash tools/install.sh [--bin-dir DIRECTORY]' \
        'Default: ~/.local/bin' \
        'Identical installations are preserved. Differing files and symlinks are refused.'
}
if (( BASH_VERSINFO[0] < 3 || (BASH_VERSINFO[0] == 3 && BASH_VERSINFO[1] < 2) )); then
    ga_install_fail 'Bash 3.2 or newer is required.'
fi
GA_INSTALL_ROOT=$(CDPATH= cd -P -- "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
GA_INSTALL_SOURCE="$GA_INSTALL_ROOT/bin/git-agent"
GA_INSTALL_DIR="${HOME:?HOME must identify the user home directory}/.local/bin"
ga_explicit=0
while (( $# )); do
    case "$1" in
        --help|-h) ga_install_usage; exit 0 ;;
        --bin-dir)
            (( $# >= 2 )) || ga_install_fail '--bin-dir needs a directory path.'
            GA_INSTALL_DIR=$2; ga_explicit=1; shift 2 ;;
        *) ga_install_fail "Unrecognized argument: $1" ;;
    esac
done
[[ -n "$GA_INSTALL_DIR" && "$GA_INSTALL_DIR" != *[[:cntrl:]]* ]] || ga_install_fail 'Installation directory must be nonempty and contain no control characters.'
[[ "$GA_INSTALL_DIR" = /* ]] || GA_INSTALL_DIR="$PWD/$GA_INSTALL_DIR"
for ga_utility in cat chmod cmp dirname git ln mkdir mktemp rm rmdir; do
    command -v "$ga_utility" >/dev/null 2>&1 || ga_install_fail "Required standard utility is missing: $ga_utility"
done
ga_git_version=$(git --version) || ga_install_fail 'Git is unavailable.'
if [[ "$ga_git_version" =~ ^git[[:space:]]version[[:space:]]([0-9]+)\.([0-9]+) ]]; then
    (( BASH_REMATCH[1] > 2 || (BASH_REMATCH[1] == 2 && BASH_REMATCH[2] >= 31) )) || ga_install_fail 'Git 2.31 or newer is required.'
else
    ga_install_fail 'Could not identify Git 2.31 or newer.'
fi
[[ -f "$GA_INSTALL_SOURCE" && ! -L "$GA_INSTALL_SOURCE" ]] || ga_install_fail 'Build bin/git-agent first with bash tools/build.sh.'
if ! {
    IFS= read -r ga_first
    IFS= read -r ga_second
} < "$GA_INSTALL_SOURCE"; then
    ga_install_fail 'bin/git-agent is incomplete; rebuild to an empty output path.'
fi
[[ "$ga_first" = '#!/usr/bin/env bash' && "$ga_second" = '# git-agent standalone Bash bundle; generated by tools/build.sh' ]] || ga_install_fail 'bin/git-agent is not the expected standalone Bash build; rebuild to an empty output path.'
"$BASH" -n "$GA_INSTALL_SOURCE" || ga_install_fail 'Built command failed Bash syntax validation.'

ga_found=$(type -P git-agent || :)
if [[ "$ga_explicit" = 0 && -n "$ga_found" ]]; then
    ga_found_dir=$(CDPATH= cd -P -- "$(dirname "$ga_found")" && pwd -P)
    ga_found="$ga_found_dir/git-agent"
    ga_default="$GA_INSTALL_DIR/git-agent"
    if [[ -d "$GA_INSTALL_DIR" ]]; then
        ga_default="$(CDPATH= cd -P -- "$GA_INSTALL_DIR" && pwd -P)/git-agent"
    fi
    [[ "$ga_found" = "$ga_default" ]] || ga_install_fail "Another git-agent resolves on PATH: $ga_found. Choose an explicit --bin-dir after deciding which command to use."
fi

# An existing parent may intentionally be reached through a symlink (for example
# macOS /tmp). Resolve and report the actual parent; never follow a leaf symlink.
mkdir -p "$GA_INSTALL_DIR" || ga_install_fail "Cannot create installation directory: $GA_INSTALL_DIR"
GA_INSTALL_DIR=$(CDPATH= cd -P -- "$GA_INSTALL_DIR" && pwd -P)
GA_INSTALL_TARGET="$GA_INSTALL_DIR/git-agent"
[[ ! -L "$GA_INSTALL_TARGET" ]] || ga_install_fail "Refusing an existing symlink: $GA_INSTALL_TARGET"
if [[ -e "$GA_INSTALL_TARGET" ]]; then
    [[ -f "$GA_INSTALL_TARGET" ]] || ga_install_fail "Destination is not a regular file: $GA_INSTALL_TARGET"
    cmp -s "$GA_INSTALL_SOURCE" "$GA_INSTALL_TARGET" || ga_install_fail "Refusing to replace existing content: $GA_INSTALL_TARGET. Choose an empty --bin-dir or inspect and remove the confirmed prior installation first."
    [[ -x "$GA_INSTALL_TARGET" ]] || ga_install_fail "Identical destination is not executable: $GA_INSTALL_TARGET"
    printf 'Already installed; no file changed: %s\n' "$GA_INSTALL_TARGET"
else
    GA_INSTALL_TEMP=''
    ga_install_cleanup() {
        if [[ -n "$GA_INSTALL_TEMP" && -d "$GA_INSTALL_TEMP" && ! -L "$GA_INSTALL_TEMP" ]]; then
            rm -f "$GA_INSTALL_TEMP/git-agent"
            rmdir "$GA_INSTALL_TEMP" 2>/dev/null || :
        fi
    }
    trap ga_install_cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    GA_INSTALL_TEMP=$(mktemp -d "$GA_INSTALL_DIR/.git-agent-install.XXXXXX") || ga_install_fail 'Could not create private staging directory.'
    cat "$GA_INSTALL_SOURCE" > "$GA_INSTALL_TEMP/git-agent" || ga_install_fail 'Could not stage the complete command.'
    chmod 755 "$GA_INSTALL_TEMP/git-agent" || ga_install_fail 'Could not make the staged command executable.'
    if ! (CDPATH= cd -P -- "$GA_INSTALL_DIR" && ln "./${GA_INSTALL_TEMP##*/}/git-agent" .); then
        if [[ ! -L "$GA_INSTALL_TARGET" && -f "$GA_INSTALL_TARGET" && -x "$GA_INSTALL_TARGET" ]] && cmp -s "$GA_INSTALL_SOURCE" "$GA_INSTALL_TARGET"; then
            printf 'Concurrent identical install already published: %s\n' "$GA_INSTALL_TARGET"
        else
            ga_install_fail "Could not publish $GA_INSTALL_TARGET without replacing content. Check collisions, directory permissions, and filesystem hard-link support."
        fi
    else
        printf 'Installed: %s\n' "$GA_INSTALL_TARGET"
    fi
fi
printf '%s\n' 'One Bash executable installed; no supporting runtime archive is required.' \
    'No shell profile, PATH, Git configuration, or repository was changed.'
printf 'Make this directory available on PATH: %s\n' "$GA_INSTALL_DIR"
printf '%s\n' 'Then verify: git agent --version'
