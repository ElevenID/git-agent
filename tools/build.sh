#!/usr/bin/env bash
# Build the complete command with Bash, Git, and stock Unix utilities.
set -euo pipefail

ga_build_fail() { printf 'Build failed: %s\n' "$*" >&2; exit 2; }
ga_build_usage() {
    printf '%s\n' 'Usage: bash tools/build.sh [--output FILE]' \
        'Default output: bin/git-agent' \
        'Identical output is preserved; differing output is never replaced.'
}

if (( BASH_VERSINFO[0] < 3 || (BASH_VERSINFO[0] == 3 && BASH_VERSINFO[1] < 2) )); then
    ga_build_fail 'Bash 3.2 or newer is required.'
fi
GA_BUILD_ROOT=$(CDPATH= cd -P -- "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
GA_BUILD_OUTPUT="$GA_BUILD_ROOT/bin/git-agent"
while (( $# )); do
    case "$1" in
        --help|-h) ga_build_usage; exit 0 ;;
        --output)
            (( $# >= 2 )) || ga_build_fail '--output needs a file path.'
            GA_BUILD_OUTPUT=$2; shift 2 ;;
        *) ga_build_fail "Unrecognized argument: $1" ;;
    esac
done
[[ -n "$GA_BUILD_OUTPUT" && "$GA_BUILD_OUTPUT" != *[[:cntrl:]]* ]] || ga_build_fail 'Output must be a nonempty path without control characters.'
[[ "$GA_BUILD_OUTPUT" = /* ]] || GA_BUILD_OUTPUT="$PWD/$GA_BUILD_OUTPUT"
GA_BUILD_PARENT=${GA_BUILD_OUTPUT%/*}
GA_BUILD_NAME=${GA_BUILD_OUTPUT##*/}
[[ -n "$GA_BUILD_NAME" && "$GA_BUILD_NAME" != . && "$GA_BUILD_NAME" != .. ]] || ga_build_fail 'Output must name a file.'

for ga_utility in cat chmod cmp dirname git ln mkdir mktemp rm rmdir; do
    command -v "$ga_utility" >/dev/null 2>&1 || ga_build_fail "Required standard utility is missing: $ga_utility"
done
[[ -f "$GA_BUILD_ROOT/src/git-agent.sh" && ! -L "$GA_BUILD_ROOT/src/git-agent.sh" ]] || ga_build_fail 'Expected regular source file src/git-agent.sh.'
[[ -d "$GA_BUILD_ROOT/templates" && ! -L "$GA_BUILD_ROOT/templates" ]] || ga_build_fail 'Expected real templates directory.'
[[ ! -L "$GA_BUILD_OUTPUT" ]] || ga_build_fail "Refusing an existing symlink: $GA_BUILD_OUTPUT"
if [[ -e "$GA_BUILD_OUTPUT" && ! -f "$GA_BUILD_OUTPUT" ]]; then
    ga_build_fail "Output is not a regular file: $GA_BUILD_OUTPUT"
fi

ga_build_template_paths() {
    printf '%s\n' \
        '.agents/skills/work-goal/SKILL.md' \
        '.agents/skills/work-goal/references/release-lifecycle.md' \
        '.agents/skills/work-goal/references/review-guide.md' \
        '.agents/skills/work-goal/references/state-report.md' \
        '.agents/skills/worktree-flow/SKILL.md' \
        '.agents/skills/worktree-flow/references/isolation-and-recovery.md' \
        '.codex/agents/adversarial-reviewer.toml' \
        '.codex/agents/contract-reviewer.toml' \
        '.codex/config.toml' \
        'AGENTS.md' \
        'ARCHITECTURE.md' \
        'DEVELOPMENT.md' \
        'GOVERNANCE.md' \
        'PLANS.md' \
        'docs/agent-init/README.md'
}

# Validate all source assets before creating output directories. The read builtin
# retains terminal newlines, allowing quoted heredocs to reproduce exact bytes.
while IFS= read -r ga_relative; do
    ga_source="$GA_BUILD_ROOT/templates/$ga_relative"
    ga_probe=$ga_source
    while [[ "$ga_probe" != "$GA_BUILD_ROOT/templates" ]]; do
        [[ ! -L "$ga_probe" ]] || ga_build_fail "Refusing a template symlink: $ga_probe"
        ga_probe=${ga_probe%/*}
    done
    [[ -f "$ga_source" ]] || ga_build_fail "Missing regular template: $ga_relative"
    ga_text=''
    if IFS= read -r -d '' ga_text < "$ga_source"; then
        ga_build_fail "Template contains a NUL byte: $ga_relative"
    fi
    [[ "$ga_text" = *$'\n' ]] || ga_build_fail "Template must end in an LF newline: $ga_relative"
done < <(ga_build_template_paths)

mkdir -p "$GA_BUILD_PARENT" || ga_build_fail "Cannot create output directory: $GA_BUILD_PARENT"
GA_BUILD_PARENT=$(CDPATH= cd -P -- "$GA_BUILD_PARENT" && pwd -P)
GA_BUILD_OUTPUT="$GA_BUILD_PARENT/$GA_BUILD_NAME"
GA_BUILD_TEMP=''
ga_build_cleanup() {
    if [[ -n "$GA_BUILD_TEMP" && -d "$GA_BUILD_TEMP" && ! -L "$GA_BUILD_TEMP" ]]; then
        rm -f "$GA_BUILD_TEMP/$GA_BUILD_NAME"
        rmdir "$GA_BUILD_TEMP" 2>/dev/null || :
    fi
}
trap ga_build_cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
GA_BUILD_TEMP=$(mktemp -d "$GA_BUILD_PARENT/.git-agent-build.XXXXXX") || ga_build_fail 'Could not create private staging directory.'
ga_staged="$GA_BUILD_TEMP/$GA_BUILD_NAME"
{
    printf '%s\n' '#!/usr/bin/env bash' '# git-agent standalone Bash bundle; generated by tools/build.sh'
    cat "$GA_BUILD_ROOT/src/git-agent.sh"
    printf '\n%s\n' '# Literal repository templates. Do not evaluate their contents.' 'ga_template_paths() {' "    cat <<'GIT_AGENT_TEMPLATE_PATHS_END'"
    ga_build_template_paths
    printf '%s\n' 'GIT_AGENT_TEMPLATE_PATHS_END' '}' 'ga_template_body() {' '    case "$1" in'
    ga_index=0
    while IFS= read -r ga_relative; do
        ga_index=$((ga_index + 1))
        ga_source="$GA_BUILD_ROOT/templates/$ga_relative"
        ga_text=''
        IFS= read -r -d '' ga_text < "$ga_source" || :
        ga_marker="GIT_AGENT_LITERAL_TEMPLATE_${ga_index}_END"
        while [[ $'\n'"$ga_text" = *$'\n'"$ga_marker"$'\n'* ]]; do
            ga_marker="${ga_marker}_"
        done
        # Paths are the fixed list above; bodies are never expanded or sourced.
        printf "        '%s') cat <<'%s'\n" "$ga_relative" "$ga_marker"
        cat "$ga_source"
        printf '%s\n' "$ga_marker" '            ;;'
    done < <(ga_build_template_paths)
    printf '%s\n' '        *) printf "Unknown embedded template: %s\\n" "$1" >&2; return 2 ;;' '    esac' '}' '' 'main "$@"'
} > "$ga_staged"
"$BASH" -n "$ga_staged" || ga_build_fail 'Generated command failed Bash syntax validation.'
chmod 755 "$ga_staged" || ga_build_fail 'Could not make the generated command executable.'

if [[ -L "$GA_BUILD_OUTPUT" ]]; then
    ga_build_fail "Refusing an existing symlink: $GA_BUILD_OUTPUT"
elif [[ -e "$GA_BUILD_OUTPUT" ]]; then
    [[ -f "$GA_BUILD_OUTPUT" ]] || ga_build_fail "Output is not a regular file: $GA_BUILD_OUTPUT"
    cmp -s "$ga_staged" "$GA_BUILD_OUTPUT" || ga_build_fail "Different output already exists: $GA_BUILD_OUTPUT. Choose an empty --output path, or inspect and remove the prior generated output before rebuilding."
    [[ -x "$GA_BUILD_OUTPUT" ]] || ga_build_fail "Identical output exists but is not executable: $GA_BUILD_OUTPUT"
    printf 'Already built; no file changed: %s\n' "$GA_BUILD_OUTPUT"
else
    # With destination '.', ln calculates the final basename exactly once. A
    # colliding directory cannot become a directory for the temporary filename.
    if ! (CDPATH= cd -P -- "$GA_BUILD_PARENT" && ln "./${GA_BUILD_TEMP##*/}/$GA_BUILD_NAME" .); then
        if [[ ! -L "$GA_BUILD_OUTPUT" && -f "$GA_BUILD_OUTPUT" && -x "$GA_BUILD_OUTPUT" ]] && cmp -s "$ga_staged" "$GA_BUILD_OUTPUT"; then
            printf 'Concurrent identical build already published: %s\n' "$GA_BUILD_OUTPUT"
        else
            ga_build_fail "Could not publish $GA_BUILD_OUTPUT without replacing content. Check collisions, directory permissions, and filesystem hard-link support."
        fi
    else
        printf 'Built: %s\n' "$GA_BUILD_OUTPUT"
    fi
fi
ga_identity=$(GIT_DEFAULT_HASH=sha1 GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null git --git-dir=/dev/null hash-object --no-filters "$GA_BUILD_OUTPUT") || ga_build_fail 'Could not calculate Git blob identity.'
printf 'Git blob identity (SHA-1): %s\n' "$ga_identity"
